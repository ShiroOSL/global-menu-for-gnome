let dataByCategory = null;
function getDataByCategory() {
    if (dataByCategory) return dataByCategory;
    dataByCategory = new Map();
    for (const cat of CATEGORIES) dataByCategory.set(cat.id, []);
    for (const [emoji, name, keywords, category] of EMOJI_DATA) {
        let bucket = dataByCategory.get(category);
        if (bucket) bucket.push({ emoji, name, keywords, category });
    }
    return dataByCategory;
}

function getAllEntries() {
    return EMOJI_DATA.map(([emoji, name, keywords, category]) => ({ emoji, name, keywords, category }));
}

// Floating emoji & symbols picker: search bar, category tabs, wrapping
// grid of emoji buttons. Clicking an emoji copies it to the clipboard
// and pastes it into the currently focused app, same as the clipboard
// history panel.
export class EmojiPicker {
    constructor() {
        this._actor = null;
        this._gridBox = null;
        this._searchEntry = null;
        this._activeCategory = 'all';
        this._categoryButtons = new Map();
    }

    _ensureBuilt() {
        if (this._actor) return;

        this._actor = new St.BoxLayout({
            style_class: 'globalmenu-emoji-panel popup-menu-content',
            vertical: true,
            reactive: true,
            visible: false,
        });

        // Header: title + close button.
        let header = new St.BoxLayout({ style_class: 'globalmenu-emoji-header' });
        let title = new St.Label({
            text: 'Emoji & Symbols',
            style_class: 'globalmenu-emoji-title popup-subtitle-menu-item',
            x_expand: true,
            y_align: Clutter.ActorAlign.CENTER,
        });
        header.add_child(title);

        let closeBtn = new St.Button({
            style_class: 'globalmenu-emoji-closebtn button',
            child: new St.Icon({ icon_name: 'window-close-symbolic', icon_size: 14 }),
        });
        closeBtn.connect('clicked', () => this.close());
        header.add_child(closeBtn);
        this._actor.add_child(header);

        // Search bar.
        this._searchEntry = new St.Entry({
            style_class: 'globalmenu-emoji-search',
            hint_text: 'Search emoji…',
            can_focus: true,
            x_expand: true,
        });
        let searchIcon = new St.Icon({ icon_name: 'edit-find-symbolic', icon_size: 14, style_class: 'globalmenu-emoji-search-icon' });
        this._searchEntry.set_primary_icon(searchIcon);
        this._searchEntry.clutter_text.connect('text-changed', () => this._render());
        this._actor.add_child(this._searchEntry);

        // Category tabs. Text labels (not emoji glyphs) so they render
        // reliably regardless of font/emoji fallback at small sizes.
        let tabsScroll = new St.ScrollView({
            style_class: 'globalmenu-emoji-tabs-scroll',
            hscrollbar_policy: St.PolicyType.EXTERNAL,
            vscrollbar_policy: St.PolicyType.NEVER,
        });
        let tabs = new St.BoxLayout({ style_class: 'globalmenu-emoji-tabs' });

        let allTab = this._makeCategoryTab('all', 'All');
        tabs.add_child(allTab);
        for (const cat of CATEGORIES) {
            tabs.add_child(this._makeCategoryTab(cat.id, cat.label));
        }
        tabsScroll.set_child(tabs);
        this._actor.add_child(tabsScroll);
        this._setActiveTab('all');

        // Grid: a plain vertical box of manually-wrapped rows. (Clutter's
        // flow layout isn't reliably available across shell versions, so
        // we build rows ourselves and re-wrap them on render.)
        this._scroll = new St.ScrollView({
            style_class: 'globalmenu-emoji-scroll',
            overlay_scrollbars: true,
        });
        this._gridBox = new St.BoxLayout({
            style_class: 'globalmenu-emoji-grid',
            vertical: true,
            x_expand: true,
        });
        this._scroll.set_child(this._gridBox);
        this._actor.add_child(this._scroll);

        Main.uiGroup.add_child(this._actor);
    }

    _makeCategoryTab(id, label) {
        let btn = new St.Button({
            style_class: 'globalmenu-emoji-tab button',
        });
        // Build the label ourselves instead of using St.Button's `label:`
        // shorthand — the shorthand's internal label wasn't reliably
        // exposing clutter_text at construction time, so our ellipsize-off
        // fix was silently never applying (that's what was showing as
        // "…" for every tab, regardless of theme).
        let labelActor = new St.Label({
            text: label,
            y_align: Clutter.ActorAlign.CENTER,
        });
        labelActor.clutter_text.set_line_wrap(false);
        labelActor.clutter_text.set_ellipsize(0); // PANGO_ELLIPSIZE_NONE
        btn.set_child(labelActor);
        btn.connect('clicked', () => {
            this._activeCategory = id;
            this._setActiveTab(id);
            this._render();
        });
        this._categoryButtons.set(id, btn);
        return btn;
    }

    _setActiveTab(id) {
        for (const [tabId, btn] of this._categoryButtons) {
            if (tabId === id) {
                btn.add_style_class_name('globalmenu-emoji-tab-active');
            } else {
                btn.remove_style_class_name('globalmenu-emoji-tab-active');
            }
        }
    }

    _render() {
        if (!this._gridBox) return;
        this._gridBox.destroy_all_children();

        let query = this._searchEntry.get_text().trim().toLowerCase();
        let entries;

        if (query.length > 0) {
            // Search overrides category filtering, across all categories.
            entries = getAllEntries().filter(e =>
                e.name.includes(query) || e.keywords.includes(query)
            );
        } else if (this._activeCategory === 'all') {
            entries = getAllEntries();
        } else {
            entries = getDataByCategory().get(this._activeCategory) || [];
        }

        if (entries.length === 0) {
            let empty = new St.Label({
                text: 'No emoji found',
                style_class: 'globalmenu-emoji-empty popup-inactive-menu-item',
            });
            this._gridBox.add_child(empty);
            return;
        }

        const COLUMNS = 8;
        let row = null;
        entries.forEach((entry, i) => {
            if (i % COLUMNS === 0) {
                row = new St.BoxLayout({ style_class: 'globalmenu-emoji-row', x_expand: true });
                this._gridBox.add_child(row);
            }
            row.add_child(this._makeEmojiButton(entry));
        });
    }

    _makeEmojiButton(entry) {
        let btn = new St.Button({
            style_class: 'globalmenu-emoji-btn button',
            label: entry.emoji,
            can_focus: true,
        });
        btn.connect('clicked', () => {
            this._insert(entry.emoji);
            this.close();
        });
        return btn;
    }

    _insert(char) {
        St.Clipboard.get_default().set_text(St.ClipboardType.CLIPBOARD, char);
        try {
            let seat = Clutter.get_default_backend().get_default_seat();
            let virtualDevice = seat.create_virtual_device(Clutter.InputDeviceType.KEYBOARD_DEVICE);
            if (!virtualDevice) return;
            let ctrlScanCode = 29;
            let vScanCode = 47;
            GLib.timeout_add(GLib.PRIORITY_DEFAULT, 60, () => {
                let t = GLib.get_monotonic_time();
                virtualDevice.notify_key(t, ctrlScanCode, Clutter.KeyState.PRESSED);
                virtualDevice.notify_key(t + 10, vScanCode, Clutter.KeyState.PRESSED);
                virtualDevice.notify_key(t + 20, vScanCode, Clutter.KeyState.RELEASED);
                virtualDevice.notify_key(t + 30, ctrlScanCode, Clutter.KeyState.RELEASED);
                return GLib.SOURCE_REMOVE;
            });
        } catch (e) {
            // Ignore; clipboard is still set even if synthesized paste fails.
        }
    }

    _positionNear(sourceActor) {
        if (!sourceActor) return;
        let [x, y] = sourceActor.get_transformed_position();
        let sourceHeight = sourceActor.get_height();
        let monitor = Main.layoutManager.findMonitorForActor(sourceActor)
            || Main.layoutManager.primaryMonitor;

        let panelWidth = 420;
        let panelHeight = 480;
        this._actor.set_size(panelWidth, panelHeight);

        let posX = Math.round(x);
        let posY = Math.round(y + sourceHeight + 6);

        if (monitor) {
            if (posX + panelWidth > monitor.x + monitor.width)
                posX = monitor.x + monitor.width - panelWidth - 8;
            if (posX < monitor.x) posX = monitor.x + 8;
            if (posY + panelHeight > monitor.y + monitor.height)
                posY = Math.round(y) - panelHeight - 6;
        }

        this._actor.set_position(posX, posY);
    }

    toggle(sourceActor) {
        if (this._actor && this._actor.visible) {
            this.close();
        } else {
            this.open(sourceActor);
        }
    }

    open(sourceActor) {
        this._ensureBuilt();
        this._searchEntry.set_text('');
        this._activeCategory = 'all';
        this._setActiveTab('all');
        this._render();
        this._positionNear(sourceActor);
        this._actor.show();
        Main.uiGroup.set_child_above_sibling(this._actor, null);
        // Defer focus to the next idle tick: this panel is opened from a
        // PopupMenu item activation, and the menu's own close/grab-release
        // can steal key focus back if we set it in the same frame.
        GLib.idle_add(GLib.PRIORITY_DEFAULT, () => {
            if (this._actor && this._actor.visible && this._searchEntry) {
                global.stage.set_key_focus(this._searchEntry);
            }
            return GLib.SOURCE_REMOVE;
        });
    }

    close() {
        if (this._actor) this._actor.hide();
    }

    destroy() {
        this.close();
        if (this._actor) {
            this._actor.destroy();
            this._actor = null;
        }
    }
}
